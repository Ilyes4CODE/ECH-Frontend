  t(key) {
    return this.data[this.lang]?.[key] ?? this.data.fr?.[key] ?? key;
  },

  setLang(l) {
    this.lang = l;
    localStorage.setItem('lang', l);
    document.documentElement.setAttribute('lang', l);
    document.documentElement.setAttribute('dir', l === 'ar' ? 'rtl' : 'ltr');
    this.applyAll();
    document.querySelectorAll('[data-lang-btn]').forEach(b => {
      b.classList.toggle('active', b.dataset.langBtn === l);
    });
    document.dispatchEvent(new CustomEvent('lang-change', {detail:{lang:l}}));
  },

  applyAll() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      const val = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = val;
      else el.textContent = val;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.placeholder = this.t(el.dataset.i18nPh);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.dataset.i18nTitle);
      if (el.tagName === 'TITLE') document.title = this.t(el.dataset.i18nTitle) + ' — ECH SAHARA ERP';
    });
  },

  init() {
    this.setLang(this.lang);
  }
